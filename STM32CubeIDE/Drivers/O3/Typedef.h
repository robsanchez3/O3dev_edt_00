#ifndef TYPEDEF_H_
#define TYPEDEF_H_

#include <stdint.h>

typedef uint8_t   uint8;
typedef uint16_t  uint16;
typedef uint32_t  uint32;

typedef int8_t    int8;
typedef int16_t   int16;
typedef int32_t   int32;

#ifndef FALSE
#define FALSE   0
#endif
#ifndef TRUE
#define TRUE    1
#endif

#endif /* TYPEDEF_H_ */
